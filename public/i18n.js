// Langue choisie (enregistrée dans le navigateur), sinon celle du navigateur.
const LANG = (() => {
  let saved = null;
  try { saved = localStorage.getItem('sd-lang'); } catch { /* stockage indisponible */ }
  if (I18N[saved]) return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
})();
const LOCALE = LANG === 'fr' ? 'fr-FR' : 'en-US';

function t(key, vars = {}) {
  const text = I18N[LANG][key] ?? I18N.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

// Pluriel : clé.one / clé.other. En français, 0 et 1 sont au singulier.
function tp(key, count, vars = {}) {
  const one = count === 1 || (LANG === 'fr' && count === 0);
  return t(`${key}.${one ? 'one' : 'other'}`, { count, ...vars });
}

// Message d'une erreur de l'API : traduit si le serveur a fourni un code connu.
function errMsg(e) {
  return e?.code && I18N[LANG][`err.${e.code}`] ? t(`err.${e.code}`, e.params || {}) : (e?.message || String(e));
}

function setLang(lang) {
  try { localStorage.setItem('sd-lang', lang); } catch { /* stockage indisponible */ }
  location.reload();
}

// Traduit le HTML statique : data-i18n (texte), data-i18n-html (HTML de confiance,
// issu de ce fichier), data-i18n-placeholder, data-i18n-title, data-i18n-aria.
function applyStaticI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
